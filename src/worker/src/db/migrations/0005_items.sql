CREATE TABLE items (
  id TEXT PRIMARY KEY NOT NULL,
  user_id TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('note', 'table', 'memo')),
  topic_id TEXT,
  group_id TEXT,
  title TEXT,
  content_markdown TEXT,
  content_ciphertext BLOB,
  tags_json TEXT NOT NULL CHECK (json_valid(tags_json) AND json_type(tags_json) = 'array'),
  attachment_hashes_json TEXT NOT NULL CHECK (json_valid(attachment_hashes_json) AND json_type(attachment_hashes_json) = 'array'),
  status TEXT CHECK (status IS NULL OR status IN ('todo', 'doing', 'done')),
  source TEXT NOT NULL,
  rev INTEGER NOT NULL CHECK (rev >= 0),
  meta_rev INTEGER NOT NULL CHECK (meta_rev >= 0),
  content_hash TEXT NOT NULL,
  pinned INTEGER NOT NULL DEFAULT 0 CHECK (pinned IN (0, 1)),
  starred INTEGER NOT NULL DEFAULT 0 CHECK (starred IN (0, 1)),
  enc_self INTEGER NOT NULL DEFAULT 0 CHECK (enc_self IN (0, 1)),
  in_enc_space INTEGER NOT NULL DEFAULT 0 CHECK (in_enc_space IN (0, 1)),
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  deleted_at INTEGER,
  UNIQUE (user_id, id),
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (user_id, topic_id) REFERENCES topic_nodes (user_id, id),
  FOREIGN KEY (user_id, group_id) REFERENCES topic_nodes (user_id, id),
  CHECK (group_id IS NULL OR topic_id IS NOT NULL),
  CHECK (type = 'memo' OR title IS NOT NULL),
  CHECK (type != 'memo' OR (enc_self = 0 AND in_enc_space = 0)),
  CHECK ((enc_self = 0 AND in_enc_space = 0 AND content_markdown IS NOT NULL AND content_ciphertext IS NULL)
      OR (enc_self + in_enc_space = 1 AND content_markdown IS NULL AND content_ciphertext IS NOT NULL))
)
